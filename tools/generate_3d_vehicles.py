#!/usr/bin/env python3
"""
MODULE 31 — Procedural 3D Vehicle .OBJ Mesh Generator
Ultra Car Simulator / Car Parking Game
Generates real .obj + .mtl files for multiple vehicle classes.
Production-grade geometry engine with vertices, normals, UVs, and faces.
"""

import math
import os
import sys
from dataclasses import dataclass, field
from typing import List, Tuple, Dict, Optional

OUTPUT_DIR = os.path.join(os.path.dirname(__file__), "..", "client", "Assets", "Models", "Vehicles")
os.makedirs(OUTPUT_DIR, exist_ok=True)

Vector3 = Tuple[float, float, float]
Vector2 = Tuple[float, float]

@dataclass
class MeshData:
    name: str
    vertices: List[Vector3] = field(default_factory=list)
    normals: List[Vector3] = field(default_factory=list)
    uvs: List[Vector2] = field(default_factory=list)
    faces: List[Tuple[int, int, int]] = field(default_factory=list)
    materials: Dict[str, List[int]] = field(default_factory=dict)

    def add_vertex(self, v: Vector3) -> int:
        self.vertices.append(v)
        return len(self.vertices)

    def add_normal(self, n: Vector3) -> int:
        self.normals.append(n)
        return len(self.normals)

    def add_uv(self, uv: Vector2) -> int:
        self.uvs.append(uv)
        return len(self.uvs)

    def add_face(self, v1: int, v2: int, v3: int, mat: str = "default"):
        self.faces.append((v1, v2, v3))
        if mat not in self.materials:
            self.materials[mat] = []
        self.materials[mat].append(len(self.faces))

    def compute_normals(self):
        self.normals = [(0.0, 0.0, 0.0)] * len(self.vertices)
        for a, b, c in self.faces:
            va = self.vertices[a-1]
            vb = self.vertices[b-1]
            vc = self.vertices[c-1]
            nx = (vb[1]-va[1])*(vc[2]-va[2]) - (vb[2]-va[2])*(vc[1]-va[1])
            ny = (vb[2]-va[2])*(vc[0]-va[0]) - (vb[0]-va[0])*(vc[2]-va[2])
            nz = (vb[0]-va[0])*(vc[1]-va[1]) - (vb[1]-va[1])*(vc[0]-va[0])
            length = math.sqrt(nx*nx + ny*ny + nz*nz) or 1.0
            n = (nx/length, ny/length, nz/length)
            for idx in (a-1, b-1, c-1):
                self.normals[idx] = (
                    self.normals[idx][0] + n[0],
                    self.normals[idx][1] + n[1],
                    self.normals[idx][2] + n[2]
                )
        for i in range(len(self.normals)):
            nx, ny, nz = self.normals[i]
            length = math.sqrt(nx*nx + ny*ny + nz*nz) or 1.0
            self.normals[i] = (nx/length, ny/length, nz/length)

    def write_obj(self, path: str):
        self.compute_normals()
        with open(path, "w") as f:
            f.write(f"# Generated by MODULE 31 — {self.name}\n")
            f.write(f"o {self.name}\n")
            for v in self.vertices:
                f.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
            for n in self.normals:
                f.write(f"vn {n[0]:.6f} {n[1]:.6f} {n[2]:.6f}\n")
            for uv in self.uvs:
                f.write(f"vt {uv[0]:.6f} {uv[1]:.6f}\n")
            for a, b, c in self.faces:
                f.write(f"f {a}//{a} {b}//{b} {c}//{c}\n")
        print(f"[MODULE 31] Wrote {path} ({len(self.vertices)} verts, {len(self.faces)} faces)")

    def write_mtl(self, path: str):
        with open(path, "w") as f:
            f.write("# Generated materials\n")
            f.write("newmtl body_paint\nKd 0.8 0.1 0.1\nKs 0.5 0.5 0.5\nNs 100\n")
            f.write("newmtl glass\nKd 0.2 0.3 0.4\nKs 0.9 0.9 0.9\nNs 200\nd 0.4\n")
            f.write("newmtl rubber\nKd 0.05 0.05 0.05\n")
            f.write("newmtl metal\nKd 0.6 0.6 0.65\nKs 0.8 0.8 0.8\nNs 150\n")
        print(f"[MODULE 31] Wrote {path}")

def box(mesh: MeshData, min_p: Vector3, max_p: Vector3, mat: str = "body_paint"):
    x0,y0,z0 = min_p
    x1,y1,z1 = max_p
    base = len(mesh.vertices)
    pts = [
        (x0,y0,z0), (x1,y0,z0), (x1,y1,z0), (x0,y1,z0),
        (x0,y0,z1), (x1,y0,z1), (x1,y1,z1), (x0,y1,z1)
    ]
    for p in pts:
        mesh.add_vertex(p)
        mesh.add_uv((0.0, 0.0))
    faces = [
        (0,1,2),(0,2,3), (4,6,5),(4,7,6),
        (0,4,5),(0,5,1), (2,6,7),(2,7,3),
        (0,3,7),(0,7,4), (1,5,6),(1,6,2)
    ]
    for a,b,c in faces:
        mesh.add_face(base+a+1, base+b+1, base+c+1, mat)

def cylinder(mesh: MeshData, center: Vector3, radius: float, height: float, segments: int = 16, mat: str = "rubber"):
    cx, cy, cz = center
    base = len(mesh.vertices)
    mesh.add_vertex((cx, cy + height/2, cz))
    mesh.add_uv((0.5, 1.0))
    mesh.add_vertex((cx, cy - height/2, cz))
    mesh.add_uv((0.5, 0.0))
    for i in range(segments):
        ang = 2 * math.pi * i / segments
        x = cx + radius * math.cos(ang)
        z = cz + radius * math.sin(ang)
        mesh.add_vertex((x, cy + height/2, z))
        mesh.add_uv((i/segments, 1.0))
        mesh.add_vertex((x, cy - height/2, z))
        mesh.add_uv((i/segments, 0.0))
    for i in range(segments):
        n = (i+1) % segments
        t1 = base + 3 + i*2
        t2 = base + 3 + n*2
        b1 = base + 4 + i*2
        b2 = base + 4 + n*2
        mesh.add_face(base+1, t1, t2, mat)
        mesh.add_face(base+2, b2, b1, mat)
        mesh.add_face(t1, b1, b2, mat)
        mesh.add_face(t1, b2, t2, mat)

def generate_hypercar() -> MeshData:
    m = MeshData("hypercar_chiron_body")
    box(m, (-1.1, 0.15, -2.4), (1.1, 0.85, 2.2), "body_paint")
    box(m, (-0.95, 0.85, -0.8), (0.95, 1.35, 1.1), "glass")
    box(m, (-1.05, 0.7, 1.1), (1.05, 0.95, 2.3), "body_paint")
    box(m, (-1.0, 0.6, -2.5), (1.0, 0.9, -1.6), "body_paint")
    box(m, (-1.2, 1.1, -2.6), (1.2, 1.25, -2.2), "body_paint")
    for sx, sz in [(-0.95, 1.4), (0.95, 1.4), (-0.95, -1.6), (0.95, -1.6)]:
        cylinder(m, (sx, 0.35, sz), 0.38, 0.25, 20, "rubber")
        cylinder(m, (sx, 0.35, sz), 0.18, 0.28, 12, "metal")
    cylinder(m, (0.35, 1.05, 0.4), 0.18, 0.05, 12, "metal")
    return m

