def generate_yacht() -> MeshData:
    m = MeshData("superyacht_hull")
    for i in range(24):
        t = i / 23
        z = -12 + t * 24
        w = 2.2 * (1 - abs(t-0.5)*1.4)
        h = 1.2 * (1 - t*0.3)
        box(m, (-w, 0.0, z), (w, h, z+1.0), "body_paint")
    box(m, (-1.8, 1.2, -2.0), (1.8, 3.5, 6.0), "body_paint")
    box(m, (-1.5, 3.5, 0.0), (1.5, 5.0, 4.0), "glass")
    return m

